import { test, expect } from '@playwright/test';
import path from 'node:path';

test.use({ viewport: { width: 1280, height: 800 }, video: { mode: 'on', size: { width: 1280, height: 800 } } });
test('record the real synthetic review workflow for the submission demo', async ({ page }) => {
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill('assessor@example.test');
  await page.getByLabel('Password', { exact: true }).fill(process.env.DEMO_PASSWORD || 'local-demo-only-2026');
  await page.waitForTimeout(1200);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page).toHaveURL(/\/assessments$/);
  await page.waitForTimeout(1200);
  await page.getByText('Backend engineering | synthetic demo', { exact: true }).click();
  await page.getByRole('button', { name: 'Results', exact: true }).waitFor();
  await page.waitForTimeout(1200);
  await page.getByRole('button', { name: 'Results', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Portfolio Results' })).toBeVisible();
  await page.waitForTimeout(1800);
  await page.getByRole('combobox').click();
  await page.getByRole('option', { name: 'Backend Engineer | synthetic demo' }).click();
  await page.waitForTimeout(1200);
  await page.getByRole('button', { name: /Run Fit\/Gap Analysis/ }).click();
  await expect(page.getByText('3 of 4 requirements assessed')).toBeVisible();
  await page.waitForTimeout(2000);
  const row = page.getByRole('row').filter({ hasText: 'RESTful API Design' });
  await row.locator('summary').click();
  await expect(row).toContainText('Human reviewed');
  await expect(row).toContainText('Synthetic human review');
  await page.waitForTimeout(2000);
  await page.getByLabel('Needs follow-up only').check();
  await expect(page.getByRole('row').filter({ hasText: 'Communication' })).toBeVisible();
  await page.waitForTimeout(1800);
  await page.getByLabel('Needs follow-up only').uncheck();
  await page.getByRole('button', { name: 'Refresh comparison', exact: true }).click();
  await expect(page.getByText('Preparing your comparison')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Download PDF' })).toBeEnabled();
  await page.waitForTimeout(1500);
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download PDF' }).click();
  expect(await (await download).failure()).toBeNull();
  await page.getByRole('link', { name: 'View transcript', exact: true }).click();
  await expect(page).toHaveURL(/\/transcript$/);
  await page.waitForTimeout(1500);
  const video = page.video();
  await page.context().close();
  await video?.saveAs(path.resolve('../assessment/demo/public/workflow.webm'));
});
