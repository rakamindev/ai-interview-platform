# frozen_string_literal: true

require 'rails_helper'

# AC4.1, AC4.5: one shape for every fit/gap report the API returns, including reports stored
# before this change. contracts/fit_gap_report.example.json is the shared contract; the web test
# suite renders the same file, so a rename on either side fails a test.
RSpec.describe FitGap::ReportSerializer do
  let(:contract) { JSON.parse(Rails.root.join('../contracts/fit_gap_report.example.json').read) }
  let(:org) { create(:organization) }
  let(:portfolio) { create(:portfolio, organization: org) }
  let(:vacancy) { create(:vacancy, organization: org) }

  def serialize(report)
    JSON.parse(described_class.call(report).to_json)
  end

  context 'with a report generated by the current engine' do
    let(:report) do
      create(:vacancy_skill, vacancy: vacancy, skill_id: 'SK-ENG-001', skill_label: 'React', expected_level: 2)
      create(:portfolio_skill, portfolio: portfolio, skill_id: 'SK-ENG-001', skill_label: 'React', ai_level: 3)
      FitGap::Engine.new(portfolio: portfolio, vacancy: vacancy, gemini_client: FakeGeminiClient.new({})).call
    end

    it 'has exactly the keys of the shared contract' do
      json = serialize(report)

      expect(json.keys).to match_array(contract.keys)
      expect(json['skill_comparisons'].first.keys).to match_array(contract['skill_comparisons'].first.keys)
    end

    it 'is not stale or outdated' do
      expect(serialize(report)).to include('stale' => false, 'outdated' => false)
    end

    it 'is outdated once an assessor overrides a rating after it was generated' do
      generated_at = report.generated_at
      AssessorOverride.create!(portfolio_skill: portfolio.portfolio_skills.first, ai_level: 3, override_level: 4,
                               overridden_by: 1, overridden_at: generated_at + 1.minute)

      expect(serialize(report)['outdated']).to be(true)
    end
  end

  context 'with a report stored before this change' do
    let(:report) do
      create(:fit_gap_report, portfolio: portfolio, vacancy: vacancy, rules_version: 1,
                              skill_comparisons: [{ 'skill_label' => 'React', 'skill_id' => 'SK-ENG-001',
                                                    'expected_level' => 2, 'candidate_level' => 1,
                                                    'result' => 'gap', 'delta' => -1 }])
    end

    it 'fills every contract key with a safe default' do
      row = serialize(report)['skill_comparisons'].first

      expect(row.keys).to match_array(contract['skill_comparisons'].first.keys)
      expect(row).to include('expected_level' => 2, 'result' => 'gap', 'provisional' => false, 'overridden' => false)
    end

    it 'is marked stale, so the UI can offer to regenerate it with the current rules' do
      expect(serialize(report)['stale']).to be(true)
    end
  end
end
